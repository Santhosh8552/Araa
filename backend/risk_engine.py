from typing import Optional, Dict, Any, List, Tuple
from database import query, query_one, write, get_state, set_state

# Conservative Institutional Risk Defaults
DEFAULT_RISK_POLICY = {
    "risk_per_trade_pct": 1.5,          # 1.5% default risk per trade
    "max_risk_per_trade_pct": 5.0,      # Hard cap on single trade risk
    "max_daily_loss_usd": 250.0,        # Auto-suspend day trading at -$250
    "max_weekly_loss_usd": 750.0,       # Auto-suspend week trading at -$750
    "max_monthly_loss_usd": 2000.0,     # Auto-suspend month trading at -$2000
    "max_drawdown_pct": 15.0,           # Max equity drawdown circuit breaker (15%)
    "max_open_positions": 15,           # Conservative default cap (no unlimited bypass)
    "hard_cap_positions": 50,           # Absolute institutional ceiling
    "max_portfolio_exposure_mult": 10.0,# Total notional exposure <= 10x account equity
    "max_consecutive_losses": 5,        # Pause bot after 5 consecutive losing trades
    "max_safe_leverage": 100.0,         # CoinDCX verified max leverage ceiling
    "min_liquidation_buffer_pct": 0.80, # Distance to liquidation must exceed stop distance
    "maker_fee_bps": 2.0,               # 0.02% maker fee
    "taker_fee_bps": 5.0,               # 0.05% taker fee
    "default_slippage_bps": 3.0,        # 0.03% estimated market slippage
}


class InstitutionalRiskEngine:
    """
    Standalone risk gatekeeper. Every order—whether generated by the 3-Agent AI Committee,
    walk-forward trainer, or manual user action—must pass `evaluate_pre_trade_risk` before execution.
    """

    @staticmethod
    def get_user_risk_limits(user_id):
        user = query_one("SELECT * FROM users WHERE id=?", (user_id,)) or {}
        sub = query_one("SELECT * FROM user_subscriptions WHERE user_id=? AND status='ACTIVE'", (user_id,))
        plan_code = (sub["plan_code"] if sub else user.get("plan_code")) or "PRO"
        plan = query_one("SELECT * FROM subscription_plans WHERE plan_code=?", (plan_code,)) or {}

        plan_max_pos = int(plan.get("max_open_positions") or DEFAULT_RISK_POLICY["max_open_positions"])
        plan_max_lev = float(plan.get("max_leverage") or DEFAULT_RISK_POLICY["max_safe_leverage"])

        raw_user_pos = int(user.get("bot_max_positions") or 10)
        # Never allow unlimited (999 or <=0) to bypass institutional risk ceilings
        if raw_user_pos <= 0 or raw_user_pos > DEFAULT_RISK_POLICY["hard_cap_positions"]:
            effective_max_pos = min(plan_max_pos, DEFAULT_RISK_POLICY["hard_cap_positions"])
        else:
            effective_max_pos = min(raw_user_pos, plan_max_pos, DEFAULT_RISK_POLICY["hard_cap_positions"])

        raw_user_lev = float(user.get("bot_leverage") or 20.0)
        effective_max_lev = max(1.0, min(raw_user_lev, plan_max_lev, DEFAULT_RISK_POLICY["max_safe_leverage"]))

        raw_risk_pct = float(user.get("bot_risk_pct") or DEFAULT_RISK_POLICY["risk_per_trade_pct"])
        effective_risk_pct = max(0.25, min(raw_risk_pct, DEFAULT_RISK_POLICY["max_risk_per_trade_pct"]))

        return {
            "user_id": user_id,
            "plan_code": plan_code,
            "risk_per_trade_pct": effective_risk_pct,
            "max_open_positions": effective_max_pos,
            "max_leverage": effective_max_lev,
            "max_daily_loss_usd": float(user.get("max_daily_loss_usd") or DEFAULT_RISK_POLICY["max_daily_loss_usd"]),
            "max_weekly_loss_usd": float(user.get("max_weekly_loss_usd") or DEFAULT_RISK_POLICY["max_weekly_loss_usd"]),
            "max_drawdown_pct": float(user.get("max_drawdown_pct") or DEFAULT_RISK_POLICY["max_drawdown_pct"]),
            "max_consecutive_losses": DEFAULT_RISK_POLICY["max_consecutive_losses"],
        }

    @staticmethod
    def calculate_liquidation_price(entry_price, side, leverage, maintenance_margin_rate=0.005):
        """Calculates isolated futures liquidation price."""
        entry = float(entry_price or 0.0)
        lev = max(1.0, float(leverage or 1.0))
        if entry <= 0:
            return 0.0
        is_long = str(side).upper() in ("BUY", "LONG")
        if is_long:
            liq = entry * (1.0 - (1.0 / lev) + maintenance_margin_rate)
            return round(max(0.0, liq), 6)
        else:
            liq = entry * (1.0 + (1.0 / lev) - maintenance_margin_rate)
            return round(liq, 6)

    @staticmethod
    def calculate_volatility_adjusted_size(equity_usd, risk_pct, entry_price, stop_price, atr_value=None, max_leverage=20.0):
        """
        Volatility-based position sizing using stop distance and ATR.
        Ensures dollar loss at stop-loss never exceeds `equity_usd * (risk_pct / 100)`.
        """
        equity = max(0.0, float(equity_usd or 0.0))
        entry = float(entry_price or 0.0)
        stop = float(stop_price or 0.0)
        if equity <= 0 or entry <= 0:
            return {"qty": 0.0, "margin_usd": 0.0, "notional_usd": 0.0, "effective_leverage": 1.0}

        risk_capital_usd = equity * (float(risk_pct) / 100.0)
        stop_dist_pct = abs(entry - stop) / entry if stop > 0 else 0.015
        if atr_value and atr_value > 0:
            atr_pct = float(atr_value) / entry
            stop_dist_pct = max(stop_dist_pct, atr_pct * 1.2)
        stop_dist_pct = max(0.003, min(stop_dist_pct, 0.15))  # Clamp between 0.3% and 15%

        notional_usd = risk_capital_usd / stop_dist_pct
        max_allowed_notional = equity * min(float(max_leverage), DEFAULT_RISK_POLICY["max_portfolio_exposure_mult"])
        notional_usd = min(notional_usd, max_allowed_notional)

        eff_lev = max(1.0, min(float(max_leverage), DEFAULT_RISK_POLICY["max_safe_leverage"]))
        margin_usd = round(notional_usd / eff_lev, 4)
        # Never allocate more than 25% of total equity into a single position's margin
        if margin_usd > equity * 0.25:
            margin_usd = round(equity * 0.25, 4)
            notional_usd = round(margin_usd * eff_lev, 4)

        qty = round(notional_usd / entry, 8)
        return {
            "qty": qty,
            "margin_usd": margin_usd,
            "notional_usd": round(notional_usd, 2),
            "risk_capital_usd": round(risk_capital_usd, 2),
            "stop_distance_pct": round(stop_dist_pct * 100.0, 3),
            "effective_leverage": eff_lev,
        }

    @classmethod
    def evaluate_pre_trade_risk(cls, user_id, symbol, side, equity_usd, entry_price, stop_price, take_profit_price, requested_leverage=20.0, is_live=False):
        """
        Comprehensive independent risk gate.
        Returns (approved: bool, reason: str, details: dict)
        """
        # 1. Global Emergency Kill Switch Check
        if get_state("emergency_platform_kill_switch", "0") == "1":
            return False, "EMERGENCY_KILL_SWITCH_ACTIVE: Platform-wide trading is suspended by Administrator.", {}

        user = query_one("SELECT * FROM users WHERE id=?", (user_id,))
        if not user:
            return False, "USER_NOT_FOUND", {}
        if user.get("account_status") == "SUSPENDED":
            return False, "ACCOUNT_SUSPENDED: Trading is disabled on this account.", {}

        # 2. Check Real-Bot Emergency Shutdown
        rb_cfg = query_one("SELECT emergency_shutdown FROM real_bot_configs WHERE user_id=?", (user_id,))
        if rb_cfg and rb_cfg.get("emergency_shutdown"):
            return False, "USER_KILL_SWITCH_ACTIVE: Emergency shutdown is active on your account.", {}

        limits = cls.get_user_risk_limits(user_id)
        now = time.time()

        # 3. Check Open Position Count vs Hard Limit
        open_positions = query(
            "SELECT id, symbol, margin, leverage, qty, entry_price FROM positions WHERE user_id=? AND status IN ('OPEN', 'PENDING_BROKER')",
            (user_id,)
        )
        if len(open_positions) >= limits["max_open_positions"]:
            return False, f"MAX_POSITIONS_REACHED: {len(open_positions)}/{limits['max_open_positions']} active slots occupied.", {"limits": limits}

        # 4. Duplicate Symbol Prevention
        for p in open_positions:
            if str(p["symbol"]).upper() == str(symbol).upper():
                return False, f"DUPLICATE_SYMBOL_BLOCKED: Position already open for {symbol}.", {}

        # 5. Daily Loss, Weekly Loss, & Monthly Loss Circuit Breakers
        day_ago = now - 86400
        week_ago = now - (7 * 86400)
        month_ago = now - (30 * 86400)
        daily_row = query_one(
            "SELECT COALESCE(SUM(realized_pnl), 0.0) as pnl FROM positions WHERE user_id=? AND status='CLOSED' AND closed_at >= ?",
            (user_id, day_ago)
        )
        weekly_row = query_one(
            "SELECT COALESCE(SUM(realized_pnl), 0.0) as pnl FROM positions WHERE user_id=? AND status='CLOSED' AND closed_at >= ?",
            (user_id, week_ago)
        )
        monthly_row = query_one(
            "SELECT COALESCE(SUM(realized_pnl), 0.0) as pnl FROM positions WHERE user_id=? AND status='CLOSED' AND closed_at >= ?",
            (user_id, month_ago)
        )
        daily_pnl = float(daily_row["pnl"] or 0.0) if daily_row else 0.0
        weekly_pnl = float(weekly_row["pnl"] or 0.0) if weekly_row else 0.0
        monthly_pnl = float(monthly_row["pnl"] or 0.0) if monthly_row else 0.0
        max_monthly = float(limits.get("max_monthly_loss_usd") or DEFAULT_RISK_POLICY["max_monthly_loss_usd"])

        if daily_pnl <= -abs(limits["max_daily_loss_usd"]):
            cls._log_risk_event(user_id, symbol, "LIMIT_BREACH", "CRITICAL", "DAILY_LOSS_LIMIT", f"Daily loss limit breached (${daily_pnl:.2f})")
            cls._suspend_user_bot(user_id, f"Daily loss circuit breaker triggered (${daily_pnl:.2f} <= -${limits['max_daily_loss_usd']:.2f})")
            return False, f"DAILY_LOSS_LIMIT_REACHED: Settled 24h P&L (${daily_pnl:.2f}) breached limit (-${limits['max_daily_loss_usd']:.2f}).", {}

        if weekly_pnl <= -abs(limits["max_weekly_loss_usd"]):
            cls._log_risk_event(user_id, symbol, "LIMIT_BREACH", "CRITICAL", "WEEKLY_LOSS_LIMIT", f"Weekly loss limit breached (${weekly_pnl:.2f})")
            cls._suspend_user_bot(user_id, f"Weekly loss circuit breaker triggered (${weekly_pnl:.2f} <= -${limits['max_weekly_loss_usd']:.2f})")
            return False, f"WEEKLY_LOSS_LIMIT_REACHED: Settled 7d P&L (${weekly_pnl:.2f}) breached limit (-${limits['max_weekly_loss_usd']:.2f}).", {}

        if monthly_pnl <= -abs(max_monthly):
            cls._log_risk_event(user_id, symbol, "LIMIT_BREACH", "CRITICAL", "MONTHLY_LOSS_LIMIT", f"Monthly loss limit breached (${monthly_pnl:.2f})")
            cls._suspend_user_bot(user_id, f"Monthly loss circuit breaker triggered (${monthly_pnl:.2f} <= -${max_monthly:.2f})")
            return False, f"MONTHLY_LOSS_LIMIT_REACHED: Settled 30d P&L (${monthly_pnl:.2f}) breached limit (-${max_monthly:.2f}).", {}

        # 6. Consecutive Losses Check (300s cooldown after N consecutive strategy losses)
        recent_closed = query(
            "SELECT realized_pnl, closed_at FROM positions WHERE user_id=? AND status='CLOSED' "
            "AND COALESCE(close_reason,'') NOT IN ('USER_STOPPED_BOT','DIRECTION_SWITCH_LONG','DIRECTION_SWITCH_SHORT','POSITION_LIMIT_REDUCED') "
            "ORDER BY closed_at DESC LIMIT ?",
            (user_id, limits["max_consecutive_losses"])
        )
        if len(recent_closed) >= limits["max_consecutive_losses"] and all(float(r["realized_pnl"] or 0) < 0 for r in recent_closed):
            last_loss_at = float(recent_closed[0].get("closed_at") or 0.0)
            if last_loss_at > 0 and (now - last_loss_at) < 300.0:
                rem_s = int(300.0 - (now - last_loss_at))
                return False, f"CONSECUTIVE_LOSS_COOLDOWN: {limits['max_consecutive_losses']} consecutive losing trades detected. Cooldown active ({rem_s}s remaining).", {}

        # 7. Stop-Loss & Risk/Reward Validation
        entry = float(entry_price or 0.0)
        stop = float(stop_price or 0.0)
        tp = float(take_profit_price or 0.0)
        if entry <= 0 or stop <= 0 or tp <= 0:
            return False, "INVALID_SL_TP: Stop-loss and Take-profit prices must be strictly positive.", {}

        risk_dist = abs(entry - stop)
        reward_dist = abs(tp - entry)
        if risk_dist <= 0:
            return False, "ZERO_STOP_DISTANCE: Stop-loss cannot equal entry price.", {}

        rr_ratio = round(reward_dist / risk_dist, 2)
        if rr_ratio < 1.15:
            return False, f"INSUFFICIENT_RR_RATIO: Risk/Reward {rr_ratio}:1 is below institutional minimum (1.15:1).", {"rr_ratio": rr_ratio}

        # 8. Liquidation Distance Guard
        eff_lev = min(float(requested_leverage or 1.0), limits["max_leverage"])
        liq_price = cls.calculate_liquidation_price(entry, side, eff_lev)
        is_long = str(side).upper() in ("BUY", "LONG")
        if is_long and stop <= liq_price:
            return False, f"LIQUIDATION_HAZARD: Stop-loss ({stop}) is at or below isolated liquidation price ({liq_price}) at {eff_lev}x.", {}
        if not is_long and stop >= liq_price and liq_price > 0:
            return False, f"LIQUIDATION_HAZARD: Stop-loss ({stop}) is at or above isolated liquidation price ({liq_price}) at {eff_lev}x.", {}

        # 9. Sizing & Portfolio Exposure Check
        sizing = cls.calculate_volatility_adjusted_size(
            equity_usd=equity_usd,
            risk_pct=limits["risk_per_trade_pct"],
            entry_price=entry,
            stop_price=stop,
            max_leverage=eff_lev
        )
        current_exposure = sum(float(p["margin"] or 0) * float(p["leverage"] or 1) for p in open_positions)
        effective_exposure_mult = max(
            DEFAULT_RISK_POLICY["max_portfolio_exposure_mult"],
            eff_lev * max(1, min(5, limits["max_open_positions"])) * 0.5,
        )
        max_total_exposure = float(equity_usd or 0) * effective_exposure_mult
        if current_exposure + sizing["notional_usd"] > max_total_exposure and max_total_exposure > 0:
            return False, f"MAX_EXPOSURE_EXCEEDED: Total exposure would exceed {effective_exposure_mult:.1f}x account equity.", {}

        return True, "RISK_APPROVED", {
            "limits": limits,
            "sizing": sizing,
            "rr_ratio": rr_ratio,
            "liquidation_price": liq_price,
            "daily_pnl_usd": daily_pnl,
            "weekly_pnl_usd": weekly_pnl,
        }

    @staticmethod
    def is_global_kill_switch_active() -> bool:
        return get_state("emergency_platform_kill_switch", "0") == "1"

    @staticmethod
    def set_global_kill_switch(enabled: bool = True, reason: str = "ADMIN_ACTION"):
        set_state("emergency_platform_kill_switch", "1" if enabled else "0")
        set_state("emergency_kill_switch_reason", str(reason or "ADMIN_ACTION"))

    @staticmethod
    def set_bot_kill_switch(user_id: int, bot_id: Optional[str] = None, enabled: bool = True, reason: str = "USER_ACTION"):
        """Activates or deactivates emergency kill switch for a specific bot or user."""
        now = time.time()
        if bot_id:
            write("UPDATE trading_bots SET status=?, updated_at=? WHERE bot_id=? AND user_id=?",
                  ("PAUSED" if enabled else "ACTIVE", now, bot_id, user_id))
        write("UPDATE users SET bot_enabled=? WHERE id=?", (0 if enabled else 1, user_id))
        write(
            "INSERT INTO real_bot_configs(user_id, provider_id, bot_status, emergency_shutdown, created_at, updated_at) "
            "VALUES(?, 'COINDCX', ?, ?, ?, ?) "
            "ON CONFLICT(user_id) DO UPDATE SET bot_status=excluded.bot_status, "
            "emergency_shutdown=excluded.emergency_shutdown, updated_at=excluded.updated_at",
            (user_id, "PAUSED" if enabled else "RUNNING", 1 if enabled else 0, now, now)
        )
        write("INSERT INTO bot_log(at, user_id, level, message) VALUES(?,?,?,?)",
              (now, user_id, "KILL_SWITCH", f"🚨 BOT KILL SWITCH {'ACTIVATED' if enabled else 'DEACTIVATED'}: {reason}"))

    @classmethod
    def evaluate_user_risk_status(cls, user_id: int) -> Dict[str, Any]:
        """Comprehensive risk health evaluation for user across all limits, drawdowns, and loss ceilings."""
        limits = cls.get_user_risk_limits(user_id)
        u = query_one("SELECT * FROM users WHERE id=?", (user_id,)) or {}
        w = query_one("SELECT * FROM wallets WHERE user_id=?", (user_id,)) or {}
        equity = float(w.get("deposit_balance") or 0.0) + float(w.get("profit_balance") or 0.0)

        now_ts = time.time()
        d_row = query_one("SELECT COALESCE(SUM(realized_pnl), 0.0) as pnl FROM positions WHERE user_id=? AND status='CLOSED' AND closed_at >= ?", (user_id, now_ts - 86400))
        w_row = query_one("SELECT COALESCE(SUM(realized_pnl), 0.0) as pnl FROM positions WHERE user_id=? AND status='CLOSED' AND closed_at >= ?", (user_id, now_ts - 7 * 86400))
        m_row = query_one("SELECT COALESCE(SUM(realized_pnl), 0.0) as pnl FROM positions WHERE user_id=? AND status='CLOSED' AND closed_at >= ?", (user_id, now_ts - 30 * 86400))

        daily_pnl = round(float(d_row["pnl"] or 0.0), 2) if d_row else 0.0
        weekly_pnl = round(float(w_row["pnl"] or 0.0), 2) if w_row else 0.0
        monthly_pnl = round(float(m_row["pnl"] or 0.0), 2) if m_row else 0.0

        opens = query("SELECT * FROM positions WHERE user_id=? AND status IN ('OPEN', 'PENDING_BROKER')", (user_id,))
        open_count = len(opens)
        exposure = sum(float(p.get("margin") or 0.0) * float(p.get("leverage") or 1.0) for p in opens)

        breaches = []
        can_trade = True

        if cls.is_global_kill_switch_active():
            breaches.append("GLOBAL_KILL_SWITCH_ACTIVE")
            can_trade = False

        cfg = query_one("SELECT emergency_shutdown FROM real_bot_configs WHERE user_id=?", (user_id,))
        if cfg and cfg.get("emergency_shutdown"):
            breaches.append("BOT_KILL_SWITCH_ACTIVE")
            can_trade = False

        if daily_pnl < -limits["max_daily_loss_usd"]:
            breaches.append(f"DAILY_LOSS_BREACH: ${abs(daily_pnl):.2f} exceeds limit ${limits['max_daily_loss_usd']:.2f}")
            can_trade = False

        if weekly_pnl < -limits["max_weekly_loss_usd"]:
            breaches.append(f"WEEKLY_LOSS_BREACH: ${abs(weekly_pnl):.2f} exceeds limit ${limits['max_weekly_loss_usd']:.2f}")
            can_trade = False

        if monthly_pnl < -DEFAULT_RISK_POLICY.get("max_monthly_loss_usd", 2500.0):
            breaches.append(f"MONTHLY_LOSS_BREACH: ${abs(monthly_pnl):.2f} exceeds monthly limit")
            can_trade = False

        if open_count >= limits["max_open_positions"]:
            breaches.append(f"CAPACITY_REACHED: {open_count} open positions equal or exceed limit {limits['max_open_positions']}")

        status_label = "NORMAL"
        if not can_trade:
            status_label = "CRITICAL_BREACH"
        elif breaches:
            status_label = "WARNING"

        return {
            "user_id": user_id,
            "risk_status": status_label,
            "can_trade": can_trade,
            "limits": limits,
            "metrics": {
                "equity_usd": equity,
                "daily_pnl_usd": daily_pnl,
                "weekly_pnl_usd": weekly_pnl,
                "monthly_pnl_usd": monthly_pnl,
                "open_positions": open_count,
                "max_open_positions": limits["max_open_positions"],
                "total_exposure_usd": exposure,
                "consecutive_losses": int(u.get("consecutive_losses") or 0)
            },
            "breaches": breaches
        }

    @classmethod
    def compute_liquidation_price(cls, entry_price, side, leverage, maintenance_margin_rate=0.005):
        return cls.calculate_liquidation_price(entry_price, side, leverage, maintenance_margin_rate)

    @staticmethod
    def _suspend_user_bot(user_id, reason):
        now = time.time()
        write("UPDATE users SET bot_enabled=0 WHERE id=?", (user_id,))
        write("UPDATE real_bot_configs SET bot_status='PAUSED', updated_at=? WHERE user_id=?", (now, user_id))
        write("INSERT INTO bot_log(at, user_id, level, message) VALUES(?,?,?,?)",
              (now, user_id, "RISK_HALT", f"🛑 INSTITUTIONAL RISK ENGINE SUSPENDED BOT: {reason}"))


class OrderLifecycleManager:
    """
    Tracks every order from creation to confirmation or rejection with unique UUIDs,
    explicit fee accounting (maker/taker), slippage calculation, and funding cost estimation.
    """

    @staticmethod
    def calculate_execution_costs(notional_usd, order_type="MARKET", is_paper=True, requested_price=0.0, filled_price=0.0):
        notional = max(0.0, float(notional_usd or 0.0))
        fee_bps = DEFAULT_RISK_POLICY["taker_fee_bps"] if str(order_type).upper() == "MARKET" else DEFAULT_RISK_POLICY["maker_fee_bps"]
        fee_usd = round(notional * (fee_bps / 10000.0), 4)

        req_p = float(requested_price or 0.0)
        fill_p = float(filled_price or req_p)
        if is_paper and req_p > 0 and fill_p == req_p:
            # Simulate realistic 3 bps market slippage on paper orders
            slip_bps = DEFAULT_RISK_POLICY["default_slippage_bps"] if str(order_type).upper() == "MARKET" else 0.0
        elif req_p > 0:
            slip_bps = round(abs(fill_p - req_p) / req_p * 10000.0, 2)
        else:
            slip_bps = 0.0

        slippage_usd = round(notional * (slip_bps / 10000.0), 4)
        return {
            "fee_usd": fee_usd,
            "fee_bps": fee_bps,
            "slippage_bps": slip_bps,
            "slippage_usd": slippage_usd,
        }

    @classmethod
    def create_order_record(cls, user_id, symbol, side, requested_qty=None, requested_price=0.0, leverage=1.0,
                            margin_allocated=0.0, exchange="PAPER_SIM", execution_mode="PAPER",
                            order_type="MARKET", stop_loss=None, take_profit=None, qty=None, is_live=False):
        eff_qty = float(requested_qty if requested_qty is not None else (qty or 0.0))
        if is_live and execution_mode == "PAPER":
            execution_mode = "LIVE"
            exchange = "COINDCX"
        order_uuid = "ORD-" + uuid.uuid4().hex[:16].upper()
        now = time.time()
        liq_price = InstitutionalRiskEngine.calculate_liquidation_price(requested_price, side, leverage)
        write(
            "INSERT INTO order_audit_lifecycle("
            "order_uuid, user_id, exchange, execution_mode, symbol, side, order_type, "
            "requested_qty, requested_price, leverage, margin_allocated, liquidation_price, "
            "stop_loss, take_profit, lifecycle_state, broker_confirmed, created_at, updated_at"
            ") VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,'CREATED',0,?,?)",
            (order_uuid, user_id, exchange, execution_mode, symbol, side, order_type,
             eff_qty, requested_price, leverage, margin_allocated, liq_price,
             stop_loss, take_profit, now, now)
        )
        return order_uuid

    @classmethod
    def confirm_order_fill(cls, order_uuid, executed_price, qty=0.0, exchange_order_id=None, is_live=False, position_id=None):
        res = cls.finalize_order_record(
            order_uuid=order_uuid,
            executed=True,
            filled_qty=qty,
            filled_price=executed_price,
            position_id=position_id,
            exchange_order_id=exchange_order_id,
            broker_confirmed=bool(is_live),
            is_paper=not bool(is_live),
        )
        if not res:
            return {"order_uuid": order_uuid, "status": "NOT_FOUND", "fee_usd": 0.0, "slippage_bps": 0.0}
        res["status"] = res["lifecycle_state"]
        return res

    @classmethod
    def finalize_order_record(cls, order_uuid, executed, filled_qty, filled_price, position_id=None,
                              exchange_order_id=None, broker_confirmed=False, is_paper=True,
                              raw_response=None, error_reason=None):
        row = query_one("SELECT * FROM order_audit_lifecycle WHERE order_uuid=?", (order_uuid,))
        if not row:
            return None
        now = time.time()
        notional = float(filled_qty or 0.0) * float(filled_price or 0.0)
        costs = cls.calculate_execution_costs(
            notional_usd=notional,
            order_type=row.get("order_type", "MARKET"),
            is_paper=is_paper,
            requested_price=row.get("requested_price", 0.0),
            filled_price=filled_price
        )
        if executed and (broker_confirmed or is_paper):
            state = "FILLED_CONFIRMED" if not is_paper else "FILLED_SIMULATED"
        elif executed:
            state = "SUBMITTED_PENDING_CONFIRMATION"
        else:
            state = "REJECTED_OR_FAILED"

        write(
            "UPDATE order_audit_lifecycle SET position_id=?, filled_qty=?, filled_price=?, "
            "fee_usd=?, slippage_bps=?, lifecycle_state=?, exchange_order_id=?, broker_confirmed=?, "
            "raw_response_json=?, error_reason=?, updated_at=? WHERE order_uuid=?",
            (position_id, filled_qty, filled_price, costs["fee_usd"], costs["slippage_bps"],
             state, str(exchange_order_id or ""), 1 if broker_confirmed else 0,
             json.dumps(raw_response or {}), error_reason, now, order_uuid)
        )
        return {
            "order_uuid": order_uuid,
            "lifecycle_state": state,
            "fee_usd": costs["fee_usd"],
            "slippage_bps": costs["slippage_bps"],
            "liquidation_price": row.get("liquidation_price", 0.0)
        }


